"""Breakdown of wrong joint MC answers at N=5 (main study, E1/E2 core set).

Writes $PAPER_OUT/sec/gen_errors.tex (default work/analysis/out/paper/sec/) (\\gpudef macros) and results/joint_error_breakdown.csv.
Run from anywhere: .venv/bin/python work/analysis/error_breakdown.py

Per model, among wrong joint answers (item or country not the asked slot):
  whole  = both fields name the same wrong shown image (a whole answer lifted from it)
  half   = one field correct, the other names a distractor
  two    = both fields wrong and naming two different distractors
  other  = a field resolved to no shown image (format error / unresolved)
halfc = among half-right answers, share whose wrong field is the country
same = among answers with both fields wrong (both name distractors), share naming the same image (chance 0.25).
"""
import os, sys
from pathlib import Path
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
os.chdir(ROOT); sys.path.insert(0, ROOT)
import analyze as A
import pandas as pd

MODELS = ["gemma4", "qwen3vl", "qwen25vl", "gemma3_4b", "granite4v", "lfm25v"]
KEY = {"gemma4": "gemma4", "qwen3vl": "qwen3vl", "qwen25vl": "qwen25vl",
       "gemma3_4b": "gemmathree", "granite4v": "granite", "lfm25v": "lfm"}


def breakdown(d):
    sl, i, c = d.slot.values, d.item_slot.values, d.country_slot.values
    wrong = ~((i == sl) & (c == sl))
    shown = (i > 0) & (c > 0)
    whole = wrong & shown & (i == c) & (i != sl)
    half = wrong & shown & (i != c) & ((i == sl) | (c == sl))
    two = wrong & shown & (i != c) & (i != sl) & (c != sl)
    both = shown & (i != sl) & (c != sl)
    n = wrong.sum()
    halfc = half & (i == sl)  # half right with the item correct, i.e. the country is the wrong field
    return dict(wrong=int(n), whole=whole.sum() / n, half=half.sum() / n, two=two.sum() / n,
                other=(wrong & ~(whole | half | two)).sum() / n, both=int(both.sum()),
                same=whole.sum() / both.sum(), halfc=halfc.sum() / half.sum())


def main():
    core, _ = A.core_sets(A.load(MODELS))
    d = core[(core["mode"] == "mc") & (core.N == 5)]
    rows = [dict(model=m, **breakdown(d[d.model == m])) for m in MODELS]
    df = pd.DataFrame(rows)
    for r in rows:  # self-check: the four types partition the wrong answers
        assert abs(r["whole"] + r["half"] + r["two"] + r["other"] - 1) < 1e-9, r
    df.to_csv("results/joint_error_breakdown.csv", index=False)
    pct = lambda x: f"{100 * x:.0f}"
    out = ["% auto-generated by work/analysis/error_breakdown.py -- do not edit; re-run the script.",
           "% Wrong joint MC answers at N=5 (main study). Percent values, no % sign."]
    for r in rows:
        k = KEY[r["model"]]
        out += [f"\\gpudef{{err.{k}.n}}{{{r['wrong']}}}", f"\\gpudef{{err.{k}.both}}{{{r['both']}}}"]
        out += [f"\\gpudef{{err.{k}.{f}}}{{{pct(r[f])}}}" for f in ("whole", "half", "two", "other", "same", "halfc")]
    rest = df[df.model != "gemma4"]
    lo_hi = lambda s: f"{pct(s.min())}--{pct(s.max())}"
    no_q25 = df[df.model != "qwen25vl"]
    out += [f"\\gpudef{{err.whole.rest}}{{{lo_hi(rest.whole)}}}",
            f"\\gpudef{{err.half.range}}{{{lo_hi(df.half)}}}",
            f"\\gpudef{{err.half.nmajor}}{{{int((df.half > df[['whole', 'two', 'other']].max(axis=1)).sum())}}}",
            f"\\gpudef{{err.same.rest}}{{{lo_hi(no_q25.same)}}}",
            f"\\gpudef{{err.halfc.range}}{{{lo_hi(df.halfc)}}}",
            f"\\gpudef{{err.halfc.rest}}{{{lo_hi(df[df.model != 'gemma3_4b'].halfc)}}}"]
    out_dir = Path(os.environ.get("PAPER_OUT", "work/analysis/out/paper")).expanduser() / "sec"   # PAPER_OUT=<paper dir>
    out_dir.mkdir(parents=True, exist_ok=True)
    with open(out_dir / "gen_errors.tex", "w") as f:
        f.write("\n".join(out) + "\n")
    print(df.round(3).to_string(index=False))


if __name__ == "__main__":
    main()
