"""Reviewer checks on the main-study MC data (post-hoc, exploratory).

1. Country accuracy given a correct item, at N=1 vs N=5 (per model, target-clustered bootstrap CI on the change).
   If country-given-item accuracy is already low at N=1, half-right answers at N=5 would be a knowledge gap,
   not a binding failure.
2. The wrong-answer breakdown at N=5 (as in error_breakdown.py) after dropping letter-copy errors
   (country wrong and the country letter equals the chosen item letter).

Writes $PAPER_OUT/sec/gen_review.tex (default work/analysis/out/paper/sec/) and results/review_checks.csv.
Run: .venv/bin/python work/analysis/review_checks.py
"""
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import novel as NV  # noqa: E402  (load() adds the chosen / gold option letters)
from error_breakdown import breakdown, KEY, MODELS  # noqa: E402

os.chdir(NV.ROOT)
RNG = np.random.default_rng(0)
B = 2000


def country_given_item(g):
    """Per-target country accuracy among item-correct MC answers, at N=1 and N=5; paired over targets."""
    h = g[g.item_ok == 1]
    w = h.groupby(["target", "N"]).country_ok.mean().unstack("N")
    p1, p5 = h[h.N == 1].country_ok.mean(), h[h.N == 5].country_ok.mean()
    w = w[[1, 5]].dropna()
    d = (w[5] - w[1]).values
    bs = d[RNG.integers(0, len(d), (B, len(d)))].mean(1)
    return dict(cgi1=p1, cgi5=p5, cgid=d.mean(), lo=np.percentile(bs, 2.5), hi=np.percentile(bs, 97.5),
                n1=int((h.N == 1).sum()), n5=int((h.N == 5).sum()), paired_targets=len(d))


def main():
    df, _, _ = NV.load()
    core, _ = NV.core_sets(df)
    mc = core[core["mode"] == "mc"]
    rows = []
    for m in MODELS:
        g = mc[mc.model == m]
        r = dict(model=m, **country_given_item(g))
        d5 = g[g.N == 5]
        copy = (d5.country_ok == 0) & d5.country_let.notna() & (d5.country_let == d5.item_let)
        nc = breakdown(d5[~copy])
        r.update(copies=int(copy.sum()), **{f"nc_{k}": v for k, v in nc.items()})
        rows.append(r)
    out = pd.DataFrame(rows)
    out.to_csv("results/review_checks.csv", index=False)

    f2, pct = (lambda x: f"{x:.2f}"), (lambda x: f"{100 * x:.0f}")
    sgn = lambda x: f"{x:+.2f}".replace("-", "$-$")
    lines = ["% auto-generated by work/analysis/review_checks.py -- do not edit; re-run the script.",
             "% cgi = country accuracy among item-correct MC answers; nc_* = N=5 wrong-answer shares without letter copies."]
    for r in rows:
        k = KEY[r["model"]]
        lines += [f"\\gpudef{{rev.{k}.cgi1}}{{{f2(r['cgi1'])}}}", f"\\gpudef{{rev.{k}.cgi5}}{{{f2(r['cgi5'])}}}",
                  f"\\gpudef{{rev.{k}.cgid}}{{{sgn(r['cgid'])}}}",
                  f"\\gpudef{{rev.{k}.cgid.full}}{{{sgn(r['cgid'])} [{sgn(r['lo'])}, {sgn(r['hi'])}]}}",
                  f"\\gpudef{{rev.{k}.copies}}{{{r['copies']}}}", f"\\gpudef{{rev.{k}.nc.n}}{{{r['nc_wrong']}}}"]
        lines += [f"\\gpudef{{rev.{k}.nc.{f}}}{{{pct(r['nc_' + f])}}}" for f in ("whole", "half", "two", "other", "same", "halfc")]
    rng = lambda s: f"{f2(s.min())}--{f2(s.max())}"
    lines += [f"\\gpudef{{rev.cgi1.range}}{{{rng(out.cgi1)}}}", f"\\gpudef{{rev.cgi5.range}}{{{rng(out.cgi5)}}}",
              f"\\gpudef{{rev.nc.half.range}}{{{pct(out.nc_half.min())}--{pct(out.nc_half.max())}}}",
              f"\\gpudef{{rev.cgid.nneg}}{{{int((out.hi < 0).sum())}}}"]
    sec = Path(os.environ.get("PAPER_OUT", "work/analysis/out/paper")).expanduser() / "sec"
    sec.mkdir(parents=True, exist_ok=True)
    (sec / "gen_review.tex").write_text("\n".join(lines) + "\n")
    pd.set_option("display.width", 200)
    print(out[["model", "cgi1", "cgi5", "cgid", "lo", "hi", "copies", "nc_wrong", "nc_whole", "nc_half", "nc_two",
               "nc_other", "nc_same"]].round(3).to_string(index=False))


if __name__ == "__main__":
    main()
